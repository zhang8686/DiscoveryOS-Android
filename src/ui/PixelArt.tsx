/** The dinosaur, `size` points square. */
export function PixelDino(props: { size?: number }) {
  const size = props.size ?? 120;
  const px = size / 40;
  return (
    <Canvas
      style={{ width: size, height: size }}
      draw={(cx) => {
        // Grey-black on the light surface, white-grey on the dark one: readable either way.
        const body = colorScheme() === "dark" ? "#d8dee6" : "#3a3f45";
        for (let y = 0; y < DINO.length; y++) {
          const row = DINO[y];
          for (let x = 0; x < row.length; x++) {
            if (row[x] !== "#") continue;
            cx.fillStyle = body;
            cx.fillRect(x * px, y * px, px, px);
          }
        }
      }}
    />
  );
}
